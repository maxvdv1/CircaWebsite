// Generates the hero map: Mercator land + country borders from Natural Earth 110m (world-atlas).
import { geoMercator, geoPath } from 'd3-geo'
import { feature, mesh } from 'topojson-client'
import { readFileSync, writeFileSync } from 'node:fs'
const W = 3072
const R = W / (2 * Math.PI)
const LAT = 80
const yTop = W / 2 - R * Math.log(Math.tan(Math.PI / 4 + (LAT * Math.PI) / 360))
const H = Math.round(W - 2 * yTop)
const topo = JSON.parse(readFileSync('node_modules/world-atlas/countries-110m.json', 'utf8'))
const land = feature(topo, topo.objects.land)
const borders = mesh(topo, topo.objects.countries, (a, b) => a !== b)
const proj = geoMercator().scale(R).translate([W / 2, W / 2 - yTop]).clipExtent([[0, 0], [W, H]]).precision(0.5)
const path = geoPath(proj).digits(0)
const out = `/** Mercator world for the hero map round. Generated by scripts/map.mjs from Natural Earth 110m (world-atlas). Do not edit. */
export const MAP_W = ${W}
export const MAP_H = ${H}
export const MAP_Y_TOP = ${yTop.toFixed(3)}
export const LAND = '${path(land)}'
export const BORDERS = '${path(borders)}'
`
writeFileSync(process.argv[2], out)
console.log('bytes', out.length, 'H', H, 'yTop', yTop)
