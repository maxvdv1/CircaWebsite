import { geoOrthographic, geoPath, geoGraticule10 } from 'd3-geo'
import { feature } from 'topojson-client'
import { readFileSync, writeFileSync } from 'node:fs'
const topo = JSON.parse(readFileSync('node_modules/world-atlas/land-110m.json','utf8'))
const land = feature(topo, topo.objects.land)
const proj = geoOrthographic().scale(98).translate([100,100]).rotate([68, 8, 0]).precision(0.3)
const path = geoPath(proj).digits(1)
const pin = proj([-72.545, -13.163])
const out = `/** Orthographic globe for the Geografie tile, generated by scripts/globe.mjs (Natural Earth 110m via world-atlas). 200 × 200. */
export const GLOBE_LAND = '${path(land)}'
export const GLOBE_GRATICULE = '${path(geoGraticule10())}'
/** Machu Picchu, projected. */
export const GLOBE_PIN = { x: ${pin[0].toFixed(1)}, y: ${pin[1].toFixed(1)} }
`
writeFileSync('/home/claude/circa-website/src/components/modes/globeData.ts', out)
console.log(out.length, pin)
